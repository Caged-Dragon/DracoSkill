"""Browser test of the whole compiler page (needs: pip install playwright && playwright install chromium).
Starts the API with a LOCAL stand-in for the sandbox plus the static frontend, then drives the page.
    python3 backend/test/browser.py
"""
import subprocess, sys, time, urllib.request, os
from playwright.sync_api import sync_playwright
env=dict(os.environ, FAKE_SNAPSHOT="1")
ROOT=os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),"..",".."))
os.chdir(ROOT)
be=subprocess.Popen(["node","test/serve-local.mjs"],cwd="backend",env=env,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
fe=subprocess.Popen([sys.executable,"-m","http.server","8000"],cwd="frontend",stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
for _ in range(60):
    try: urllib.request.urlopen("http://localhost:8787/health",timeout=1); urllib.request.urlopen("http://localhost:8000/",timeout=1); break
    except Exception: time.sleep(.2)
ok=bad=0
def check(n,c,d=""):
    global ok,bad
    if c: ok+=1; print("  PASS ",n)
    else: bad+=1; print("  FAIL ",n,str(d)[:300])
CFG=lambda r:r.fulfill(body='window.DRACOSKILL_CONFIG={BACKEND_URL:"http://localhost:8787"};',content_type="application/javascript")
def out(pg): return pg.inner_text("#out")
def run(pg, pat="ran in", t=40000):
    pg.click("#run-btn"); pg.wait_for_function("(p)=>new RegExp(p,'i').test(document.getElementById('out').innerText)",arg=pat,timeout=t)
try:
    with sync_playwright() as p:
        b=p.chromium.launch(); ctx=b.new_context(service_workers="block", viewport={"width":1360,"height":860},permissions=["clipboard-read","clipboard-write"]); pg=ctx.new_page()
        errs=[]; badreq=[]
        pg.on("pageerror",lambda e:errs.append(str(e)))
        pg.on("response",lambda r: badreq.append((r.status,r.url)) if r.status>=400 and "localhost" in r.url else None)
        pg.route("**/assets/config.js",CFG)
        pg.goto("http://localhost:8000/"); pg.wait_for_timeout(1500)
        print("start-up")
        check("five language tabs", pg.locator(".lang-tab").count()==5)
        check("status chip says 5 of 5 ready", "5 of 5" in pg.inner_text("#conn-chip"), pg.inner_text("#conn-chip"))
        check("every tab is marked ready", pg.locator(".lang-tab.ready").count()==5)
        check("no setup notice when everything is ready", pg.is_hidden("#notice"))
        check("starts on Python with its sample", pg.eval_on_selector("#code","e=>e.value").startswith("name = input"))
        print("running every language with stdin")
        for lang,fname in [("python","main.py"),("javascript","main.js"),("java","Main.java"),("c","main.c"),("cpp","main.cpp")]:
            pg.click(f'.lang-tab[data-lang="{lang}"]'); pg.fill("#stdin","Asha"); run(pg)
            check(f"{lang}: sample runs, reads stdin, file is {fname}", "Hello, Asha!" in out(pg) and pg.inner_text("#fname")==fname, out(pg))
        print("errors are shown, not hidden")
        pg.click('.lang-tab[data-lang="c"]'); pg.fill("#code","int main(){ oops }"); run(pg,"compilation failed")
        check("C compile error shown", "error" in out(pg))
        pg.click('.lang-tab[data-lang="python"]'); pg.fill("#code","raise ValueError('boom')"); run(pg,"boom")
        check("Python runtime error shown with exit code", "boom" in out(pg) and "exited with code" in out(pg), out(pg))
        pg.fill("#code","while True: pass"); run(pg,"timed out",30000)
        check("infinite loop is stopped with a clear message", "timed out" in out(pg))
        pg.fill("#code","print('x')"); pg.click("#code"); pg.keyboard.press("Control+Enter"); pg.wait_for_function("()=>document.getElementById('out').innerText.trim().startsWith('x')",timeout=20000)
        check("Ctrl+Enter runs", True)
        print("copy / clear")
        pg.click("#copy-out"); pg.wait_for_timeout(300)
        clip=pg.evaluate("navigator.clipboard.readText()"); check("Copy puts the program output on the clipboard", clip.strip()=="x", repr(clip))
        pg.click("#clear-out"); check("Clear empties the output", out(pg).strip()=="")
        print("autosave")
        pg.fill("#code","print('saved me')"); pg.wait_for_timeout(700)
        pg.click('.lang-tab[data-lang="c"]'); pg.click('.lang-tab[data-lang="python"]')
        check("code is kept when switching languages", pg.eval_on_selector("#code","e=>e.value")=="print('saved me')")
        pg.reload(); pg.wait_for_timeout(1000)
        check("code and language survive a reload", pg.eval_on_selector("#code","e=>e.value")=="print('saved me')")
        print("share link")
        pg.click('.lang-tab[data-lang="javascript"]'); pg.fill("#code","console.log('héllo ✓ 日本')"); pg.wait_for_timeout(500)
        pg.click("#share-btn"); pg.wait_for_timeout(300)
        link=pg.evaluate("navigator.clipboard.readText()")
        check("Share copies a link with language and code", "#lang=javascript&code=" in link, link)
        ctx2=b.new_context(service_workers="block", viewport={"width":1360,"height":860}); p2=ctx2.new_page(); p2.route("**/assets/config.js",CFG)
        p2.goto(link.replace("https://","http://")); p2.wait_for_timeout(1200)
        check("a fresh browser opens the link with the same code (unicode intact)", p2.eval_on_selector("#code","e=>e.value")=="console.log('héllo ✓ 日本')", p2.eval_on_selector("#code","e=>e.value"))
        check("...and on the right language tab", p2.get_attribute('.lang-tab[data-lang="javascript"]',"aria-selected")=="true")
        run(p2); check("...and it runs", "héllo ✓ 日本" in p2.inner_text("#out"), p2.inner_text("#out")); ctx2.close()
        print("download")
        pg.click('.lang-tab[data-lang="java"]'); pg.fill("#code","public class Hi { public static void main(String[] a){} }")
        with pg.expect_download() as dl: pg.click("#download-btn")
        check("Java download is named after the public class", dl.value.suggested_filename=="Hi.java", dl.value.suggested_filename)
        pg.click('.lang-tab[data-lang="python"]')
        with pg.expect_download() as dl: pg.click("#download-btn")
        check("Python download is main.py with the code in it", dl.value.suggested_filename=="main.py" and open(dl.value.path()).read()=="print('saved me')")
        print("reset")
        pg.click("#reset-btn"); check("Reset asks first", pg.inner_text("#reset-label")=="Sure?")
        pg.click("#reset-btn"); check("second click restores the sample", pg.eval_on_selector("#code","e=>e.value").startswith("name = input"))
        print("editor feel")
        pg.fill("#code","");pg.click("#code"); pg.keyboard.type("def f(x):"); pg.keyboard.press("Enter"); pg.keyboard.type("return x")
        check("auto-indent after a colon", pg.eval_on_selector("#code","e=>e.value")=="def f(x):\n    return x")
        pg.keyboard.press("Control+A"); pg.keyboard.press("Delete"); pg.keyboard.type("x"); pg.keyboard.press("Tab"); pg.keyboard.press("Control+Z")
        check("Tab then undo works", pg.eval_on_selector("#code","e=>e.value")=="x")
        pg.fill("#code","\n".join(f"v{i} = {i}" for i in range(1,301)))
        pg.eval_on_selector("#code","e=>{e.scrollTop=e.scrollHeight;e.dispatchEvent(new Event('scroll'))}"); pg.wait_for_timeout(150)
        s=pg.evaluate("()=>({t:document.getElementById('code').scrollTop,h:document.querySelector('.code-hl').scrollTop})")
        check("highlight stays aligned at the bottom of a 300-line file", abs(s['t']-s['h'])<=1, s)
        print("layout + theme")
        w0=pg.eval_on_selector(".io","e=>e.getBoundingClientRect().width"); bx=pg.locator("#split").bounding_box()
        pg.mouse.move(bx["x"]+7,bx["y"]+bx["height"]/2); pg.mouse.down(); pg.mouse.move(bx["x"]-150,bx["y"]+bx["height"]/2,steps=6); pg.mouse.up()
        w1=pg.eval_on_selector(".io","e=>e.getBoundingClientRect().width"); check("dragging the divider resizes the panels", w1>w0+80, f"{w0}->{w1}")
        pg.click("[data-theme-toggle]"); t1=pg.evaluate("document.documentElement.dataset.theme"); pg.reload(); pg.wait_for_timeout(600)
        check("theme choice is remembered", pg.evaluate("document.documentElement.dataset.theme")==t1)
        check("no failed requests to our own servers", not badreq, badreq)
        check("no uncaught JS errors", not errs, errs)
        print("server problems are explained")
        c3=b.new_context(service_workers="block", ); p3=c3.new_page(); p3.route("**/assets/config.js",CFG); p3.route("http://localhost:8787/**",lambda r:r.abort())
        p3.goto("http://localhost:8000/"); p3.wait_for_timeout(1200)
        check("chip says the server is unreachable", "unreachable" in p3.inner_text("#conn-chip").lower(), p3.inner_text("#conn-chip"))
        p3.click("#run-btn"); p3.wait_for_function("()=>/did not answer/.test(document.getElementById('out').innerText)",timeout=10000)
        check("Run explains the problem instead of hanging", not p3.is_disabled("#run-btn")); c3.close()
        c4=b.new_context(service_workers="block", ); p4=c4.new_page(); p4.route("**/assets/config.js",CFG)
        p4.route("http://localhost:8787/sandboxes",lambda r:r.fulfill(json={"sandboxes":[{"id":i,"label":l,"available":i in("python","javascript"),"verified":False,"version":None} for i,l in [("python","Python"),("javascript","JavaScript"),("java","Java"),("c","C"),("cpp","C++")]],"isolation":{"driver":"vercel-sandbox","inferred":True}},headers={"Access-Control-Allow-Origin":"*"}))
        p4.goto("http://localhost:8000/"); p4.wait_for_timeout(1200)
        check("missing compilers show a setup notice with a link", p4.is_visible("#notice") and "/setup" in p4.get_attribute("#notice a","href"), p4.inner_text("#notice"))
        check("those tabs are marked 'needs setup', not blocked", p4.locator(".lang-tab.setup").count()==3 and p4.locator(".lang-tab:disabled").count()==0); c4.close()
        b.close()
finally:
    be.terminate(); fe.terminate()
print(f"\n{ok} passed, {bad} failed"); sys.exit(1 if bad else 0)
